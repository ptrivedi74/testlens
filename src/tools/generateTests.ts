import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import type { GenerateTestsInput, GenerateTestsOutput, TestStep } from "../types.js";

function sanitizeFilename(name: string): string {
  return name.trim().toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "") || "test";
}

function playwrightStep(step: TestStep): string {
  switch (step.action) {
    case "goto":
      return `  await page.goto(${JSON.stringify(step.value ?? "/")});`;
    case "click":
      return `  await page.click(${JSON.stringify(step.target ?? "")});`;
    case "fill":
      return `  await page.fill(${JSON.stringify(step.target ?? "")}, ${JSON.stringify(step.value ?? "")});`;
    case "assertText":
      return `  await expect(page.locator(${JSON.stringify(step.target ?? "")})).toContainText(${JSON.stringify(step.value ?? "")});`;
    case "assertVisible":
      return `  await expect(page.locator(${JSON.stringify(step.target ?? "")})).toBeVisible();`;
    case "apiRequest": {
      const method = (step.method ?? "GET").toLowerCase();
      const expect = step.expectStatus != null ? `\n  expect(res.status()).toBe(${step.expectStatus});` : "";
      return `  const res = await request.${method}(${JSON.stringify(step.target ?? "")});${expect}`;
    }
    default:
      return `  // unrecognized action: ${(step as TestStep).action}`;
  }
}

function buildPlaywrightFile(input: GenerateTestsInput): string {
  const usesApi = input.steps.some((s) => s.action === "apiRequest");
  const header = usesApi
    ? `import { test, expect, request } from "@playwright/test";`
    : `import { test, expect } from "@playwright/test";`;
  const bodyLines = input.steps.map(playwrightStep).join("\n");
  const gotoBase = input.baseUrl ? `  await page.goto(${JSON.stringify(input.baseUrl)});\n` : "";

  return [
    `// Auto-generated by TestLens generate_tests. Review before relying on it in CI.`,
    header,
    "",
    `test(${JSON.stringify(input.name)}, async ({ page${usesApi ? ", request" : ""} }) => {`,
    gotoBase + bodyLines,
    `});`,
    ""
  ].join("\n");
}

function pytestStep(step: TestStep, i: number): string {
  switch (step.action) {
    case "goto":
      return `    page.goto(${JSON.stringify(step.value ?? "/")})`;
    case "click":
      return `    page.click(${JSON.stringify(step.target ?? "")})`;
    case "fill":
      return `    page.fill(${JSON.stringify(step.target ?? "")}, ${JSON.stringify(step.value ?? "")})`;
    case "assertText":
      return `    assert ${JSON.stringify(step.value ?? "")} in page.locator(${JSON.stringify(step.target ?? "")}).text_content()`;
    case "assertVisible":
      return `    assert page.locator(${JSON.stringify(step.target ?? "")}).is_visible()`;
    case "apiRequest": {
      const method = (step.method ?? "GET").toLowerCase();
      const varName = `res_${i}`;
      const expect = step.expectStatus != null ? `\n    assert ${varName}.status_code == ${step.expectStatus}` : "";
      return `    ${varName} = requests.${method}(${JSON.stringify(step.target ?? "")})${expect}`;
    }
    default:
      return `    # unrecognized action: ${(step as TestStep).action}`;
  }
}

function buildPytestFile(input: GenerateTestsInput): string {
  const usesApi = input.steps.some((s) => s.action === "apiRequest");
  const usesPage = input.steps.some((s) => s.action !== "apiRequest");
  const imports = ["# Auto-generated by TestLens generate_tests. Review before relying on it in CI."];
  if (usesApi) imports.push("import requests");
  if (usesPage) imports.push("# Requires: pip install pytest-playwright");

  const fnArgs = usesPage ? "page" : "";
  const gotoBase = input.baseUrl && usesPage ? `    page.goto(${JSON.stringify(input.baseUrl)})\n` : "";
  const body = input.steps.map(pytestStep).join("\n");
  const fnName = `test_${sanitizeFilename(input.name).replace(/-/g, "_")}`;

  return [...imports, "", `def ${fnName}(${fnArgs}):`, gotoBase + body, ""].join("\n");
}

export async function generateTests(input: GenerateTestsInput): Promise<GenerateTestsOutput> {
  const outDir = input.outputDir ?? "generated";
  await mkdir(outDir, { recursive: true });

  const base = sanitizeFilename(input.name);
  const ext = input.runner === "playwright" ? "spec.ts" : "py";
  const fileName = input.runner === "playwright" ? `${base}.${ext}` : `test_${base}.${ext}`;
  const filePath = path.join(outDir, fileName);

  const content = input.runner === "playwright" ? buildPlaywrightFile(input) : buildPytestFile(input);
  await writeFile(filePath, content, "utf-8");

  return {
    filePath,
    runner: input.runner,
    linesGenerated: content.split("\n").length,
    preview: content.length > 800 ? content.slice(0, 800) + "\n// ... truncated in preview ..." : content
  };
}
